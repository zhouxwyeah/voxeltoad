CREATE TABLE budget_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id BIGINT NOT NULL REFERENCES budget_policies(id),
    period_start TIMESTAMPTZ NOT NULL,
    period_end TIMESTAMPTZ NOT NULL CHECK (period_end > period_start),
    currency TEXT NOT NULL,
    limit_amount BIGINT NOT NULL CHECK (limit_amount >= 0),
    reserved BIGINT NOT NULL DEFAULT 0 CHECK (reserved >= 0),
    committed BIGINT NOT NULL DEFAULT 0 CHECK (committed >= 0),
    released BIGINT NOT NULL DEFAULT 0 CHECK (released >= 0),
    UNIQUE (policy_id,period_start)
);

CREATE TABLE billing_reservations (
    id TEXT PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    request_id TEXT NOT NULL,
    -- Immutable authenticated identity, currency, estimate and price snapshot.
    identity JSONB NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('reserved','dispatched','unknown','settled','released','released_unknown')),
    actual BIGINT CHECK (actual >= 0),
    reason TEXT NOT NULL DEFAULT '',
    version BIGINT NOT NULL DEFAULT 1,
    -- Durable known result, including Usage; independent of async usage_records.
    result JSONB,
    result_applied BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
