CREATE INDEX idx_billing_reservations_stale ON billing_reservations(updated_at) WHERE status IN ('reserved','dispatched');
CREATE INDEX idx_billing_reservations_pending ON billing_reservations(updated_at) WHERE result IS NOT NULL AND NOT result_applied;

